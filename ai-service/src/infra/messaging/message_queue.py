from __future__ import annotations

import json
from typing import TYPE_CHECKING, Any

import aio_pika
from aio_pika import ExchangeType, IncomingMessage
from aio_pika.abc import AbstractRobustChannel, AbstractRobustConnection

from core.config import Settings
from infra.messaging.consumers.movie_event_handler import MovieEventHandler
from infra.messaging.event_constant import MessageEventBus, MessageEventType
from utils.logger import setup_logger


class MessageQueue:
    """RabbitMQ retry with broker-managed x-death (no client republishing).

    Main movie exchange (topic, e.g. movie.#)
      -> recommendation.queue                  [attempt 0]
         on nack(False) -> retry.1 (TTL 10s)
      -> recommendation.queue.attempt.1        [attempt 1]
         on nack(False) -> retry.2 (TTL 20s)
      -> recommendation.queue.attempt.2        [attempt 2]
         on nack(False) -> retry.3 (TTL 40s)
      -> recommendation.queue.attempt.3        [attempt 3]
         on nack(False) -> DLQ

    Each retry queue has NO consumer. Its TTL and DLX route the very same
    broker-managed message to the next processing queue. RabbitMQ maintains
    x-death for every queue expiration/rejection; we count only retry TTL
    expirations to find how many delays were completed.
    """

    RETRY_DELAYS_MS = (10_000, 20_000, 40_000)

    def __init__(self, settings: Settings) -> None:
        self._settings = settings
        self._connection: AbstractRobustConnection | None = None
        self._channel: AbstractRobustChannel | None = None
        self._consumer_tags: list[tuple[Any, str]] = []
        self._handler: MovieEventHandler | None = None
        self._logger = setup_logger(name="FastAPI-Recommendations")

    def set_handler(self, handler: MovieEventHandler) -> None:
        self._handler = handler

    def _attempt_queue(self, prefix: str, attempt: int) -> str:
        """attempt queue

        Args:
            attempt (int): _description_

        Returns:
            str: prefix for attempt queue names, e.g. "recommendation.queue" or "recommendation.queue.attempt.1"
        """
        base = prefix
        return base if attempt == 0 else f"{base}.attempt.{attempt}"

    def _retry_queue(self, prefix: str, number: int) -> str:
        """retry queue

        Args:
            number (int): _description_

        Returns:
            str: prefix for retry queue names, e.g. "recommendation.queue.retry.1"
        """
        return f"{prefix}.retry.{number}"

    def _retry_exchange_name(self, prefix: str) -> str:
        """Routing ex name

        Returns:
            str: prefix for retry routing keys, e.g. "recommendation.queue.retry.exchange"
        """
        return f"{prefix}.retry.exchange"

    @staticmethod
    def _retry_count(message: IncomingMessage, retry_names: set[str]) -> int:
        """Count expiration events on OUR retry queues only.

        x-death is generated by RabbitMQ. It may include entries for main
        queue rejections as well; those do not represent completed retries.
        """
        entries = (message.headers or {}).get("x-death", [])
        if not isinstance(entries, (list, tuple)):
            return 0

        total = 0
        for entry in entries:
            if not isinstance(entry, dict):
                continue
            queue = entry.get("queue")
            reason = entry.get("reason")
            if isinstance(queue, bytes):
                queue = queue.decode("utf-8", errors="replace")
            if isinstance(reason, bytes):
                reason = reason.decode("utf-8", errors="replace")
            if queue in retry_names and reason == "expired":
                total += int(entry.get("count", 0))
        return total

    async def start(self) -> None:
        if not self._settings.rabbitmq_enabled:
            self._logger.info("RabbitMQ disabled; consumer not started")
            return

        if self._handler is None:
            raise RuntimeError("Call set_handler(handler) before MessageQueue.start()")

        try:
            self._connection = await aio_pika.connect_robust(
                self._settings.rabbitmq_url
            )
            self._channel = await self._connection.channel(publisher_confirms=True)
            await self._channel.set_qos(prefetch_count=10)

            # External exchange for *new* events.
            movie_exchange = await self._channel.declare_exchange(
                name=MessageEventBus.MOVIE_EXCHANGE,
                type=ExchangeType.TOPIC,
                durable=True,
            )

            # Internal routing between processing/retry queues.
            routing_exchange = await self._channel.declare_exchange(
                name=self._retry_exchange_name(
                    MessageEventBus.MOVIE_RECOMMENDATION_QUEUE
                ),
                type=ExchangeType.DIRECT,
                durable=True,
            )

            # Final dead-letter destination.
            dlx = await self._channel.declare_exchange(
                name=MessageEventBus.MOVIE_DLX,
                type=ExchangeType.TOPIC,
                durable=True,
            )
            dlq = await self._channel.declare_queue(
                name=MessageEventBus.MOVIE_DLQ,
                durable=True,
            )
            await dlq.bind(
                dlx,
                routing_key=MessageEventBus.MOVIE_DLQ_RK,
            )

            # Declare *all* destinations before consuming. All DLX hops happen
            # entirely at the broker, so original x-death remains broker-managed.
            processing_queues = []
            for attempt in range(len(self.RETRY_DELAYS_MS) + 1):
                if attempt < len(self.RETRY_DELAYS_MS):
                    # Nếu chưa là queue cuối cùng thì chưa vào DLQ chính mà vào các queue retry để chờ delay TTL
                    dlx_name = self._retry_exchange_name(
                        prefix=MessageEventBus.MOVIE_RECOMMENDATION_QUEUE
                    )
                    dlx_routing_key = f"retry.{attempt + 1}"
                else:
                    # Nếu là queue cuối cùng thì vào DLQ chính
                    dlx_name = MessageEventBus.MOVIE_DLX
                    dlx_routing_key = MessageEventBus.MOVIE_DLQ_RK

                queue = await self._channel.declare_queue(
                    self._attempt_queue(
                        prefix=MessageEventBus.MOVIE_RECOMMENDATION_QUEUE,
                        attempt=attempt,
                    ),
                    durable=True,
                    arguments={
                        "x-dead-letter-exchange": dlx_name,
                        "x-dead-letter-routing-key": dlx_routing_key,
                    },
                )
                processing_queues.append(queue)

                if attempt == 0:
                    # Nếu là main queue thì bind vào movie exchange
                    # routing key movie.# để nhận tất cả các event của movie
                    await queue.bind(
                        exchange=movie_exchange,
                        routing_key=MessageEventBus.MOVIE_ROUTING_KEY,
                    )
                else:
                    # Nếu là các queue retry thì bind vào retry exchange
                    await queue.bind(
                        exchange=routing_exchange,
                        routing_key=f"attempt.{attempt}",
                    )

            # Các retry queue: nơi message chờ khi failed lần trước và khi hết hạn sẽ tự động qua các queue attempt
            # Với dlx là attempt.{number}
            for number, delay_ms in enumerate(self.RETRY_DELAYS_MS, start=1):
                retry_queue = await self._channel.declare_queue(
                    self._retry_queue(
                        prefix=MessageEventBus.MOVIE_RECOMMENDATION_QUEUE, number=number
                    ),
                    durable=True,
                    arguments={
                        "x-message-ttl": delay_ms,
                        "x-dead-letter-exchange": self._retry_exchange_name(
                            prefix=MessageEventBus.MOVIE_RECOMMENDATION_QUEUE
                        ),
                        "x-dead-letter-routing-key": f"attempt.{number}",
                    },
                )
                await retry_queue.bind(
                    exchange=routing_exchange,
                    routing_key=f"retry.{number}",
                )
                # Do NOT consume from retry queues; TTL must expire.

            for attempt, queue in enumerate(processing_queues):
                tag = await queue.consume(
                    self._handle_message,
                    no_ack=False,
                )
                self._consumer_tags.append((queue, tag))

            self._logger.info(
                "RabbitMQ ready: processing=%s; retry_ms=%s; dlq=%s",
                [
                    self._attempt_queue(
                        prefix=MessageEventBus.MOVIE_RECOMMENDATION_QUEUE, attempt=i
                    )
                    for i in range(len(processing_queues))
                ],
                self.RETRY_DELAYS_MS,
                MessageEventBus.MOVIE_DLQ,
            )
        except Exception:
            await self.close()
            raise

    async def close(self) -> None:
        # Closing a robust connection causes unacked deliveries to be requeued.
        for queue, tag in self._consumer_tags:
            try:
                await queue.cancel(tag)
            except Exception:
                self._logger.exception("Failed to cancel RabbitMQ consumer")
        self._consumer_tags.clear()

        if self._connection is not None:
            await self._connection.close()
            self._connection = None
            self._channel = None
            self._logger.info("RabbitMQ connection closed")

    async def _handle_message(self, message: IncomingMessage) -> None:
        retry_names = {
            self._retry_queue(
                prefix=MessageEventBus.MOVIE_RECOMMENDATION_QUEUE, number=i
            )
            for i in range(1, len(self.RETRY_DELAYS_MS) + 1)
        }
        completed_retries = self._retry_count(message, retry_names)
        # First delivery => 0; each completed TTL => +1.
        try:
            body = json.loads(message.body)
            if not isinstance(body, dict):
                raise ValueError("Event must be a JSON object")

            event_type = body.get("eventType")
            payload = body.get("payload")
            if not isinstance(event_type, str) or not event_type:
                raise ValueError("eventType must be a nonempty string")
            if not isinstance(payload, dict):
                raise ValueError("payload must be a JSON object")

            if self._handler is None:
                # This is an infrastructure state, not a successful delivery.
                raise RuntimeError("MovieEventHandler is not configured")

            self._logger.info(
                "Received event=%s retry_count=%s routing_key=%s",
                event_type,
                completed_retries,
                message.routing_key,
            )
            await self._handler.handle(event_type, payload)
            await message.ack()

        except Exception:
            # Each processing queue has its own DLX destination. A rejection
            # advances to the next delay or (from attempt 3) the final DLQ.
            self._logger.exception(
                "Event failed retry_count=%s; dead-letter to next stage/DLQ",
                completed_retries,
            )
            if not message.processed:
                await message.reject(requeue=False)


